// Genicons verifies every vendored SVG and writes lazy, individually linkable getters.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

type iconEntry struct {
	Name   string `json:"name"`
	SHA256 string `json:"sha256"`
}

type iconManifest struct {
	Commit string      `json:"commit"`
	Icons  []iconEntry `json:"icons"`
}

const generatedPrefix = "// Code generated by genicons from lucide@"

func main() {
	dir := flag.String("dir", ".", "directory containing manifest.json and svg/")
	flag.Parse()
	if err := generate(*dir); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func getterName(name string) string {
	var out strings.Builder
	for part := range strings.SplitSeq(name, "-") {
		out.WriteString(strings.ToUpper(part[:1]))
		out.WriteString(part[1:])
	}
	return out.String()
}

func getterFile(name string) (string, error) {
	file := strings.ReplaceAll(name, "-", "_") + ".go"
	if file == "icons.go" || file == "generate.go" || strings.HasSuffix(file, "_test.go") {
		return "", fmt.Errorf("icon %q conflicts with a package/test file", name)
	}
	// Go treats these suffixes as platform constraints even without build tags.
	parts := strings.Split(strings.TrimSuffix(file, ".go"), "_")
	if len(parts) > 1 && slices.Contains(strings.Fields("aix android darwin dragonfly freebsd illumos ios js linux netbsd openbsd plan9 solaris wasip1 windows 386 amd64 arm arm64 loong64 mips mipsle mips64 mips64le ppc64 ppc64le riscv64 s390x wasm"), parts[len(parts)-1]) {
		// For example, robot_arm.go would silently disappear on amd64.
		file = strings.TrimSuffix(file, ".go") + "_icon.go"
	}
	return file, nil
}

func generate(dir string) error {
	data, err := os.ReadFile(filepath.Join(dir, "manifest.json"))
	if err != nil {
		return err
	}
	var manifest iconManifest
	if err := json.Unmarshal(data, &manifest); err != nil {
		return err
	}
	if !regexp.MustCompile(`^[0-9a-f]{40}$`).MatchString(manifest.Commit) {
		return fmt.Errorf("invalid pinned commit")
	}
	if len(manifest.Icons) == 0 {
		return fmt.Errorf("empty icon manifest")
	}
	slices.SortFunc(manifest.Icons, func(a, b iconEntry) int { return strings.Compare(a.Name, b.Name) })
	validName := regexp.MustCompile(`^[a-z]+(?:-[a-z0-9]+)*$`)
	seen, getters := map[string]bool{}, map[string]string{}
	files := map[string][]byte{}
	var catalog bytes.Buffer
	fmt.Fprintf(&catalog, "%s%s. DO NOT EDIT.\npackage lucide\nimport \"github.com/egoist/mygo/ui\"\n", generatedPrefix, manifest.Commit)
	catalog.WriteString("// Kept in a test file so consumers do not retain all getters and SVGs.\nvar generatedIconCases = []struct { name string; get func() *ui.SVG }{\n")
	// Validate the entire set before writing anything, including hash and name collisions.
	for _, icon := range manifest.Icons {
		if !validName.MatchString(icon.Name) || seen[icon.Name] {
			return fmt.Errorf("invalid or duplicate icon %q", icon.Name)
		}
		seen[icon.Name] = true
		file, err := getterFile(icon.Name)
		if err != nil {
			return err
		}
		if _, found := files[file]; found {
			return fmt.Errorf("generated filename collision: %s", file)
		}
		name := getterName(icon.Name)
		if previous, found := getters[name]; found {
			return fmt.Errorf("getter %s collides for %q and %q", name, previous, icon.Name)
		}
		getters[name] = icon.Name
		data, err := os.ReadFile(filepath.Join(dir, "svg", icon.Name+".svg"))
		if err != nil {
			return err
		}
		if fmt.Sprintf("%x", sha256.Sum256(data)) != icon.SHA256 {
			return fmt.Errorf("SVG hash mismatch: %s", icon.Name)
		}
		variable := strings.ToLower(name[:1]) + name[1:]
		source := fmt.Sprintf(`%s%s. DO NOT EDIT.
package lucide
import (
 _ "embed"

 "github.com/egoist/mygo/ui"
)
//go:embed svg/%s.svg
var %sSource []byte
var %sCache cached
// %s returns the shared, lazily parsed %q Lucide SVG. Treat it as read-only.
func %s() *ui.SVG { return %sCache.load(%sSource) }
`, generatedPrefix, manifest.Commit, icon.Name, variable, variable, name, icon.Name, name, variable, variable)
		files[file], err = format.Source([]byte(source))
		if err != nil {
			return err
		}
		fmt.Fprintf(&catalog, "{%q, %s},\n", icon.Name, name)
	}
	catalog.WriteString("}\n")
	files["icons_catalog_test.go"], err = format.Source(catalog.Bytes())
	if err != nil {
		return err
	}
	entries, err := os.ReadDir(filepath.Join(dir, "svg"))
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() {
			return fmt.Errorf("unexpected directory in SVG set: %s", entry.Name())
		}
		if strings.HasSuffix(entry.Name(), ".svg") && !seen[strings.TrimSuffix(entry.Name(), ".svg")] {
			return fmt.Errorf("SVG missing from manifest: %s", entry.Name())
		}
	}
	entries, err = os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		current, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			return err
		}
		_, output := files[entry.Name()]
		generated := bytes.HasPrefix(current, []byte(generatedPrefix))
		if output && !generated {
			return fmt.Errorf("refusing to overwrite hand-written file: %s", entry.Name())
		}
		if generated && !output {
			return fmt.Errorf("stale generated file: %s; remove it after reconciling the SVG manifest", entry.Name())
		}
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		if err := os.WriteFile(filepath.Join(dir, name), files[name], 0644); err != nil {
			return err
		}
	}
	fmt.Printf("Verified and generated %d icons at %s\n", len(manifest.Icons), manifest.Commit)
	return nil
}
