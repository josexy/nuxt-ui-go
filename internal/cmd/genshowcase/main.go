// Genshowcase registers public configuration types and enum constants. It has
// no dependency on showcase, so it can run before compiling new descriptors.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	types := map[string]*ast.TypeSpec{}
	var files []*ast.File
	paths, err := filepath.Glob(filepath.Join(*root, "*.go"))
	if err != nil {
		log.Fatal(err)
	}
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			log.Fatal(err)
		}
		files = append(files, f)
		for _, d := range f.Decls {
			if g, ok := d.(*ast.GenDecl); ok && g.Tok == token.TYPE {
				for _, s := range g.Specs {
					t := s.(*ast.TypeSpec)
					if t.Name.IsExported() {
						types[t.Name.Name] = t
					}
				}
			}
		}
	}
	var demos []struct {
		Types       []string
		Body, Setup string
	}
	raw, err := os.ReadFile(filepath.Join(*root, "internal/showcase/catalog.json"))
	if err != nil {
		log.Fatal(err)
	}
	if err = json.Unmarshal(raw, &demos); err != nil {
		log.Fatal(err)
	}
	names := map[string]bool{"AppConfig": true, "Theme": true, "ComponentTheme": true, "PartStyle": true, "Decoration": true}
	pattern := regexp.MustCompile(`nui\.([A-Za-z]\w*(?:\[string\])?)\s*\{`)
	for _, d := range demos {
		for _, name := range d.Types {
			if strings.HasSuffix(name, "Options") {
				names[name] = true
			}
		}
		for _, m := range pattern.FindAllStringSubmatch(d.Body+"\n"+d.Setup, -1) {
			base, _, _ := strings.Cut(m[1], "[")
			t, ok := types[base]
			if !ok || base == "Optional" || strings.HasSuffix(base, "State") {
				continue
			}
			if _, ok := t.Type.(*ast.StructType); ok {
				names[m[1]] = true
			}
		}
	}
	enums := map[string][]string{}
	for _, f := range files {
		for _, d := range f.Decls {
			g, ok := d.(*ast.GenDecl)
			if !ok || g.Tok != token.CONST {
				continue
			}
			current := ""
			for _, s := range g.Specs {
				v := s.(*ast.ValueSpec)
				if v.Type != nil {
					current = ""
					if id, ok := v.Type.(*ast.Ident); ok {
						if t := types[id.Name]; t != nil {
							if base, ok := t.Type.(*ast.Ident); ok && (strings.HasPrefix(base.Name, "int") || strings.HasPrefix(base.Name, "uint") || base.Name == "string") {
								current = id.Name
							}
						}
					}
				} else if len(v.Values) > 0 {
					current = ""
				}
				if current != "" {
					for _, name := range v.Names {
						if name.IsExported() {
							enums[current] = append(enums[current], name.Name)
						}
					}
				}
			}
		}
	}
	var out strings.Builder
	out.WriteString(`// Code generated by go run ./internal/cmd/genshowcase; DO NOT EDIT.
package showcase

import (
 "reflect"
 "time"

 "github.com/egoist/mygo/ui"
 nui "github.com/josexy/nuxt-ui-go"
)

var optionTypes = map[string]reflect.Type{
`)
	for _, name := range keys(names) {
		fmt.Fprintf(&out, "%q:reflect.TypeFor[nui.%s](),\n", "nui."+name, name)
	}
	out.WriteString("}\nvar enumValues = map[reflect.Type][]enumValue{\n")
	for _, name := range keys(enums) {
		fmt.Fprintf(&out, "reflect.TypeFor[nui.%s]():{", name)
		for _, member := range enums[name] {
			fmt.Fprintf(&out, "{%q,reflect.ValueOf(nui.%s)},", "nui."+member, member)
		}
		out.WriteString("},\n")
	}
	// go list -m reports an empty Dir until the module is in the cache, and this
	// generator imports no MyGo package; go mod download fetches it if needed.
	command := exec.Command("go", "mod", "download", "-json", "github.com/egoist/mygo")
	command.Dir = *root
	output, err := command.Output()
	if err != nil {
		log.Fatal(err)
	}
	var module struct{ Dir string }
	if err := json.Unmarshal(output, &module); err != nil {
		log.Fatal(err)
	}
	if module.Dir == "" {
		log.Fatal("go mod download did not report a directory for github.com/egoist/mygo")
	}
	keyFile, err := parser.ParseFile(token.NewFileSet(), filepath.Join(module.Dir, "ui", "keys.go"), nil, 0)
	if err != nil {
		log.Fatal(err)
	}
	var keyNames []string
	ast.Inspect(keyFile, func(n ast.Node) bool {
		if v, ok := n.(*ast.ValueSpec); ok {
			for _, name := range v.Names {
				if strings.HasPrefix(name.Name, "Key") {
					keyNames = append(keyNames, "ui."+name.Name)
				}
			}
		}
		return true
	})
	extra := map[string][]string{"ui.Key": keyNames, "ui.Align": {"ui.Start", "ui.Center", "ui.End", "ui.Stretch", "ui.SpaceBetween", "ui.SpaceAround", "ui.SpaceEvenly", "ui.Baseline"}, "time.Weekday": {"time.Sunday", "time.Monday", "time.Tuesday", "time.Wednesday", "time.Thursday", "time.Friday", "time.Saturday"}}
	for _, typ := range keys(extra) {
		fmt.Fprintf(&out, "reflect.TypeFor[%s]():{", typ)
		for _, name := range extra[typ] {
			fmt.Fprintf(&out, "{%q,reflect.ValueOf(%s)},", name, name)
		}
		out.WriteString("},\n")
	}
	out.WriteString("}\n")
	code, err := format.Source([]byte(out.String()))
	if err != nil {
		log.Fatal(err)
	}
	target := filepath.Join(*root, "internal/showcase/field_types_gen.go")
	existing, _ := os.ReadFile(target)
	if !bytes.Equal(existing, code) {
		if err = os.WriteFile(target, code, 0644); err != nil {
			log.Fatal(err)
		}
	}
	fmt.Printf("Registered %d public configuration types and %d enums\n", len(names), len(enums)+len(extra))
}
func keys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for key := range m {
		out = append(out, key)
	}
	slices.Sort(out)
	return out
}
